create or replace view public.dashboard_node_status_v
with (security_invoker = true)
as
with latest as (
  select distinct on (device_id)
    device_id,
    created_at,
    disease_cn,
    risk_level,
    pump_action,
    fan_action,
    system_status,
    sensor_status
  from public.diagnosis_records
  order by device_id, created_at desc
)
select
  r.device_id,
  r.display_name,
  r.region_name,
  r.crop_type,
  coalesce(l.created_at, r.last_seen_at) as last_seen_at,
  case
    when coalesce(l.created_at, r.last_seen_at) is null then 'UNKNOWN'
    when now() - coalesce(l.created_at, r.last_seen_at) <= interval '2 minutes' then 'ONLINE'
    when now() - coalesce(l.created_at, r.last_seen_at) <= interval '10 minutes' then 'RECENT'
    else 'OFFLINE'
  end as online_status,
  coalesce(l.risk_level, 'UNKNOWN') as latest_risk_level,
  coalesce(l.disease_cn, '--') as latest_disease_cn,
  coalesce(l.pump_action, '--') as latest_pump_action,
  coalesce(l.fan_action, '--') as latest_fan_action,
  coalesce(l.system_status, 'UNKNOWN') as system_status,
  coalesce(l.sensor_status, 'UNKNOWN') as sensor_status
from public.device_registry r
left join latest l on l.device_id = r.device_id
where r.is_active = true
order by r.device_id;

create or replace view public.dashboard_risk_summary_v
with (security_invoker = true)
as
select
  risk_level,
  count(*) as record_count,
  max(created_at) as latest_at
from public.diagnosis_records
group by risk_level;

create or replace view public.dashboard_heatmap_24h_v
with (security_invoker = true)
as
select
  device_id,
  date_trunc('hour', created_at) as hour_bucket,
  count(*) as record_count,
  max(case risk_level
    when 'CRITICAL' then 5
    when 'HIGH' then 4
    when 'MEDIUM_HIGH' then 3
    when 'MEDIUM' then 2
    when 'LOW' then 1
    else 0
  end) as max_risk_score,
  max(risk_level) as max_risk_level
from public.diagnosis_records
where created_at >= now() - interval '24 hours'
group by device_id, date_trunc('hour', created_at);

create or replace view public.dashboard_alerts_v
with (security_invoker = true)
as
select
  id as record_id,
  created_at,
  device_id,
  risk_level,
  disease_cn,
  alarm,
  case
    when alarm <> 'NONE' then alarm
    when liquid_level = 'LOW' then 'LOW_LIQUID'
    when confidence < 0.6 then 'LOW_CONFIDENCE'
    when risk_level in ('HIGH', 'CRITICAL', 'MEDIUM_HIGH') then 'HIGH_RISK'
    else 'INFO'
  end as alert_type,
  suggestion as suggested_action
from public.diagnosis_records
where risk_level in ('HIGH', 'CRITICAL', 'MEDIUM_HIGH')
   or liquid_level = 'LOW'
   or alarm <> 'NONE'
   or confidence < 0.6
order by created_at desc;

