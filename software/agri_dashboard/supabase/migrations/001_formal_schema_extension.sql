-- Formal schema extension for STM32N647 agriculture dashboard.
-- Safe to run in Supabase SQL Editor: it never deletes or truncates data.
-- Device JSON v1.0 body is unchanged; security metadata stays in headers/secrets.

begin;

alter table public.diagnosis_records
  add column if not exists model_version text,
  add column if not exists latency_ms integer,
  add column if not exists raw_payload jsonb,
  add column if not exists system_status text not null default 'UNKNOWN',
  add column if not exists sensor_status text not null default 'UNKNOWN';

alter table public.diagnosis_records
  drop constraint if exists diagnosis_records_risk_level_check,
  add constraint diagnosis_records_risk_level_check
    check (risk_level in ('LOW', 'MEDIUM', 'MEDIUM_HIGH', 'HIGH', 'CRITICAL', 'UNKNOWN'));

alter table public.diagnosis_records
  drop constraint if exists diagnosis_records_pump_action_check,
  add constraint diagnosis_records_pump_action_check
    check (pump_action in ('ON', 'OFF', 'NONE', 'REQUEST'));

alter table public.diagnosis_records
  drop constraint if exists diagnosis_records_fan_action_check,
  add constraint diagnosis_records_fan_action_check
    check (fan_action in ('ON', 'OFF', 'NONE', 'REQUEST'));

create table if not exists public.device_registry (
  id bigint generated by default as identity primary key,
  device_id text not null unique check (device_id in ('Node01', 'Node02', 'Node03')),
  display_name text not null,
  region_name text not null,
  crop_type text not null,
  is_active boolean not null default true,
  token_version text not null default 'v1',
  last_seen_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.device_telemetry (
  id bigint generated by default as identity primary key,
  record_id bigint references public.diagnosis_records(id) on delete set null,
  device_id text not null,
  temperature_c double precision,
  humidity_percent double precision,
  light_lux double precision,
  soil_moisture_percent double precision,
  liquid_level text check (liquid_level in ('OK', 'LOW', 'UNKNOWN')),
  current_ma numeric,
  created_at timestamptz not null default now()
);

create table if not exists public.actuation_logs (
  id bigint generated by default as identity primary key,
  record_id bigint references public.diagnosis_records(id) on delete set null,
  device_id text not null,
  pump_action text not null check (pump_action in ('ON', 'OFF', 'NONE', 'REQUEST')),
  fan_action text not null check (fan_action in ('ON', 'OFF', 'NONE', 'REQUEST')),
  pump_duration_s integer not null default 0 check (pump_duration_s >= 0),
  fan_duration_s integer not null default 0 check (fan_duration_s >= 0),
  alarm text not null default 'NONE',
  safety_blocked boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.security_events (
  id bigint generated by default as identity primary key,
  device_id text,
  event_type text not null,
  severity text not null check (severity in ('INFO', 'WARN', 'HIGH', 'CRITICAL')),
  reason text not null,
  remote_addr text,
  created_at timestamptz not null default now()
);

create table if not exists public.model_versions (
  id bigint generated by default as identity primary key,
  model_name text not null,
  model_type text not null check (model_type in ('pc_yolo', 'onnx', 'stm32_npu', 'device_report')),
  class_count integer not null check (class_count > 0),
  class_mapping_json jsonb not null,
  accuracy numeric,
  is_active boolean not null default false,
  created_at timestamptz not null default now()
);

